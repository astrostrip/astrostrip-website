// Builds the public degree files (Sun text + IN REAL LIFE line only) from the full texts in ../degrees-full/.
// Rising and Moon texts stay private: the free calculator shows only the Sun reading (Sandra, 02.10.2026).
// Run from website/: node tools/build-public-degrees.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

for (const file of readdirSync(new URL('../degrees-full/', import.meta.url)).filter(f => f.endsWith('.js'))) {
  const full = (await import(new URL(`../degrees-full/${file}`, import.meta.url))).default;
  const header = readFileSync(new URL(`../degrees-full/${file}`, import.meta.url), 'utf8').split('\n').filter(l => l.startsWith('//'));
  const degrees = Object.keys(full).map(Number).sort((a, b) => a - b);
  if (degrees.length !== 30 || degrees.some((d, i) => d !== i + 1 || !full[d].sun)) throw new Error(`${file}: expected degrees 1-30 with a sun text`);
  // "life" = the IN REAL LIFE line for the Sun degree (Sandra, 02.10.2026); signs without it yet just leave it out.
  const body = degrees.map(d => `  ${d}: {\n    sun: ${JSON.stringify(full[d].sun)},\n${full[d].life ? `    life: ${JSON.stringify(full[d].life)},\n` : ''}  },`).join('\n');
  writeFileSync(new URL(`../public/assets/degrees/${file}`, import.meta.url),
    `${header.join('\n')}\n// Public file: Sun texts and IN REAL LIFE lines only. Generated by tools/build-public-degrees.mjs, do not edit by hand.\nexport default {\n${body}\n};\n`);
}
console.log('public degree files written');
